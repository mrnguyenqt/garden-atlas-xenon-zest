export function lotInfoKey(tieuKhu: string, khoanh: string, lo: string) {
  return `${tieuKhu}|${khoanh}|${lo}`;
}

export function lotInfoRows(tieuKhu: string, khoanh: string, lo: string): LotInfoRow[] {
  return LOT_INFO[lotInfoKey(tieuKhu, khoanh, lo)] ?? [];
}

export function ldlrLabel(code: string) {
  return LDLR_LABEL[code] ? `${code} · ${LDLR_LABEL[code]}` : code;
}

export function mdsdLabel(code: string) {
  return MDSD_LABEL[code] ? `${code} · ${MDSD_LABEL[code]}` : code;
}

export function communeFull(name: string) {
  return COMMUNE_LABEL[name] ?? name;
}

const TK_ALIAS: Record<string, string> = { "852": "852A", "858": "858A" };

const TK_COMMUNE: Record<string, string> = (() => {
  const counts: Record<string, Record<string, number>> = {};
  for (const [key, rows] of Object.entries(LOT_INFO)) {
    const tk = key.split("|")[0] ?? "";
    if (!tk) continue;
    counts[tk] ??= {};
    for (const [xa] of rows) {
      if (!xa) continue;
      counts[tk][xa] = (counts[tk][xa] ?? 0) + 1;
    }
  }
  const out: Record<string, string> = {};
  for (const [tk, xa] of Object.entries(counts)) {
    out[tk] = Object.entries(xa).sort((a, b) => b[1] - a[1])[0]?.[0] ?? "";
  }
  return out;
})();

export function communeByTieuKhu(tieuKhu: string) {
  const raw = TK_COMMUNE[tieuKhu] || TK_COMMUNE[TK_ALIAS[tieuKhu] ?? ""] || "";
  return raw ? communeFull(raw) : "";
}

function natCmp(a: string, b: string) {
  return a.localeCompare(b, "vi", { numeric: true, sensitivity: "base" });
}

export function statusLotTree(): Record<string, Record<string, string[]>> {
  const tree: Record<string, Record<string, string[]>> = {};
  for (const key of Object.keys(LOT_INFO)) {
    const [tk = "", kh = "", lo = ""] = key.split("|");
    if (!tk || !kh || !lo) continue;
    tree[tk] ??= {};
    const list = tree[tk][kh] ?? [];
    if (!list.includes(lo)) list.push(lo);
    tree[tk][kh] = list;
  }
  for (const khs of Object.values(tree)) {
    for (const [kh, list] of Object.entries(khs)) khs[kh] = list.sort(natCmp);
  }
  return tree;
}
